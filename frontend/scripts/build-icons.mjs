// Copies only the Material Symbols the app uses (rounded style, Apache-2.0) into
// src/components/icons/material.generated.ts. Fails if a name is missing, so
// every registered icon is verified against the installed package.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = (weight) => dirname(require.resolve(`@material-symbols/svg-${weight}/package.json`));
// Large device symbols also get weight 300; everything else weight 400 only.
const DEVICE = ["monitor", "dns", "router", "wifi_tethering", "shield"];
const UI = [
  "grid_view", "play_arrow", "table_chart", "list_alt", "wand_stars", "help", "light_mode", "dark_mode", "logout",
  "power_settings_new", "link_off", "settings_ethernet", "edit", "delete", "tune", "route", "add_circle", "close",
  "undo", "redo", "save", "download", "upload", "search", "schedule", "speed", "pause", "skip_next", "replay",
  "warning", "crisis_alert", "error", "check_circle", "hourglass_empty", "arrow_back", "visibility", "cable", "bolt",
];
const path = (weight, name, fill) => {
  const svg = readFileSync(join(root(weight), "rounded", `${name}${fill ? "-fill" : ""}.svg`), "utf8");
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((match) => match[1]).join(" ");
  if (!d) throw new Error(`no path in ${name}`);
  return d;
};
const entries = {};
for (const name of [...DEVICE, ...UI]) {
  entries[name] = { 400: [path(400, name, false), path(400, name, true)] };
  if (DEVICE.includes(name)) entries[name][300] = [path(300, name, false), path(300, name, true)];
}
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "icons", "material.generated.ts");
writeFileSync(
  out,
  `// GENERATED by scripts/build-icons.mjs from @material-symbols/svg-400/-300 (rounded), Apache-2.0. Do not edit.\n` +
    `// [outline, filled] path data, viewBox "0 -960 960 960".\n` +
    `export const MATERIAL: Record<string, Partial<Record<300 | 400, [string, string]>>> = ${JSON.stringify(entries)};\n`,
);
console.log(`wrote ${Object.keys(entries).length} icons to ${out}`);
